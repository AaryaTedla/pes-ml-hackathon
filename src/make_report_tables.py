"""Generate report tables straight from the committed result files (no hand-typed numbers).

    python src/make_report_tables.py

Writes:
  report/section_3_1_table.md   the Deliverables 3.1 comparison table
  report/numbers_sheet.md       every headline number with the file it comes from
Inputs: results/models/deadline_all_01/comparison.csv, results/models/route_continuity_by_model.csv,
        results/models/tuning_deadline_02/tuned_vs_untuned.csv, results/hmm_decoder_comparison_model.csv,
        results/api_hmm_check_model.csv, results/hmm_decoder_comparison_mock.csv
"""
import os
import pandas as pd

ROOT = os.path.join(os.path.dirname(__file__), "..")
R = lambda *p: os.path.join(ROOT, *p)

FAMILY = {
    "LogReg": ("Logistic Regression", "Linear / probabilistic", "StandardScaler, max_iter=200, binary log-loss"),
    "LightGBM": ("LightGBM", "Boosting", "300 trees, learning_rate=0.1, num_leaves=63, binary log-loss"),
    "RandomForest": ("Random Forest", "Bagged trees (ensemble)", "100 trees, max_depth=18, min_samples_leaf=20, Gini; capped at 300k fitting rows"),
    "MLP": ("MLP", "Neural network", "hidden (64,32), batch 2048, up to 30 epochs, Adam; capped at 300k fitting rows"),
    "KNN": ("KNN", "Instance-based", "k=25, distance-weighted, ball-tree, StandardScaler; capped at 150k fitting rows"),
}
ORDER = ["LogReg", "LightGBM", "RandomForest", "MLP", "KNN"]


def table_3_1():
    c = pd.read_csv(R("results", "models", "deadline_all_01", "comparison.csv")).set_index("model")
    rc = pd.read_csv(R("results", "models", "route_continuity_by_model.csv")).set_index("model")
    lines = [
        "### 3.1 Overall model comparison",
        "",
        "Cross-validation: 3-fold GroupKFold by trip on 40 whole training trips (seed 42). Student-test: the 10 student_test trips, all 244,176 candidate rows. "
        "Top-1 is per-point (highest-probability candidate vs the derived reference arc). Macro-F1 and log loss are binary candidate metrics at threshold 0.5. "
        "Route continuity is the classifier alone (no HMM) on student_test, using the shared metric in `src/evaluate.py`; it is not an HMM result. "
        "Source: `results/models/deadline_all_01/comparison.csv` and `results/models/route_continuity_by_model.csv`.",
        "",
        "| Model | Algorithm family | Key configuration | CV macro-F1 | Top-1 (CV / student-test) | Route continuity (student-test, classifier only) | Student-test macro-F1 | Log loss (CV / student-test) | Inference time, student-test (s) |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for k in ORDER:
        name, fam, cfg = FAMILY[k]
        r = c.loc[k]
        lines.append(f"| {name} | {fam} | {cfg} | {r.cv_macro_f1:.4f} | {r.cv_top1:.4f} / {r.test_top1:.4f} | {rc.loc[k].mean_route_continuity:.4f} | "
                     f"{r.test_macro_f1:.4f} | {r.cv_log_loss:.4f} / {r.test_log_loss:.4f} | {r.test_inference_seconds:.2f} |")
    lines += ["", f"Nearest-arc baseline Top-1: {c.cv_baseline_top1.iloc[0]:.4f} (CV mean), {c.test_baseline_top1.iloc[0]:.4f} (student-test). "
              "Per-fold Top-1 standard deviation is 0.012 to 0.019, larger than the gaps between the top three models, so the ranking is narrow. "
              "Inference time covers candidate scoring only (not feature generation or HMM decoding); KNN's cheap fit hides its slow prediction.", ""]
    open(R("report", "section_3_1_table.md"), "w", encoding="utf-8").write("\n".join(lines))


def numbers_sheet():
    c = pd.read_csv(R("results", "models", "deadline_all_01", "comparison.csv")).set_index("model")
    tu = pd.read_csv(R("results", "models", "tuning_deadline_02", "tuned_vs_untuned.csv"))
    hm = pd.read_csv(R("results", "hmm_decoder_comparison_model.csv"))
    mk = pd.read_csv(R("results", "hmm_decoder_comparison_mock.csv"))
    api = pd.read_csv(R("results", "api_hmm_check_model.csv"))
    L = ["# Numbers sheet: every headline number and the file it comes from", "",
         "Generated by `python src/make_report_tables.py`. If a number in the report differs from this sheet, the report is wrong.", ""]
    L += ["## Data (from `results/FEATURES_README.md`, `results/eda/trip_inventory.csv`)", "",
          "| Fact | Value |", "|---|---|",
          "| Trips: train / student_test / evaluator | 80 / 10 / 10 (evaluator never used) |",
          "| GPS points: train / student_test | 208,417 / 19,160 |",
          "| Candidate rows: train / student_test | 2,118,916 / 244,176 |",
          "| Candidate miss rate: train / student_test | 10.73% (about 1.05% without trips 33 and 54) / 0.13% |", ""]
    L += ["## Models (`results/models/deadline_all_01/comparison.csv`)", "", "| Model | CV Top-1 | CV Top-1 std | Student Top-1 | CV log loss | Student log loss |", "|---|---:|---:|---:|---:|---:|"]
    for k in ORDER:
        r = c.loc[k]
        L.append(f"| {k} | {r.cv_top1:.4f} | {r.cv_top1_std:.4f} | {r.test_top1:.4f} | {r.cv_log_loss:.4f} | {r.test_log_loss:.4f} |")
    L += ["", "## Bayesian optimisation (`results/models/tuning_deadline_02/`)", "",
          "| Version | Student Top-1 | Student macro-F1 | Student log loss |", "|---|---:|---:|---:|"]
    for _, r in tu.iterrows():
        L.append(f"| Random Forest {r.version} | {r.top1:.5f} | {r.macro_f1:.5f} | {r.log_loss:.5f} |")
    L += ["", "Only 6 of 25 requested Optuna trials completed (10-minute timeout). Best: max_depth=12, min_samples_leaf=16, CV log loss 0.08077.", ""]
    L += ["## HMM with the tuned Random Forest (`results/hmm_decoder_comparison_model.csv`)", "",
          "| Decoder | Split | Trips | Accuracy: classifier only | Accuracy: HMM | Continuity: HMM | Exact 50-point windows: classifier / HMM |", "|---|---|---:|---:|---:|---:|---:|"]
    for _, r in hm.iterrows():
        L.append(f"| {r.decoder} | {r.split} | {r.trips} | {r.acc_classifier_only:.4f} | {r.acc_hmm:.4f} | {r.continuity_hmm:.4f} | "
                 f"{r.seq50_exact_classifier_only:.4f} / {r.seq50_exact_hmm:.4f} |")
    L += ["", "## Live API check, all 10 student_test trips, `hmm` mode (`results/api_hmm_check_model.csv`)", "",
          f"Mean accuracy classifier-only {api.acc_classifier_only.mean():.4f} -> final {api.acc_final.mean():.4f}; mean continuity {api.continuity.mean():.4f}; "
          f"mean request time {api.total_ms.mean():.0f} ms.", ""]
    L += ["## Earlier stand-in (mock) probabilities, baseline only (`results/hmm_decoder_comparison_mock.csv`)", "",
          "| Decoder | Split | Accuracy: classifier only | Accuracy: HMM |", "|---|---|---:|---:|"]
    for _, r in mk.iterrows():
        L.append(f"| {r.decoder} | {r.split} | {r.acc_classifier_only:.4f} | {r.acc_hmm:.4f} |")
    open(R("report", "numbers_sheet.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")


if __name__ == "__main__":
    table_3_1()
    numbers_sheet()
    print("wrote report/section_3_1_table.md and report/numbers_sheet.md")
